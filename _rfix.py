import io
NL=chr(10)
def rw(p, pairs, req=True):
    t=io.open(p,encoding='utf-8').read()
    for a,b in pairs:
        if req: assert a in t, (p, a[:70])
        t=t.replace(a,b,1)
    io.open(p,'w',encoding='utf-8',newline=NL).write(t); print('patched',p)

